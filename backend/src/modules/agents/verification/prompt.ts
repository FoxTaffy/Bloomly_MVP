/** Текст досье. Данные пользователя — в отдельном блоке <user_data>, JSON-строкой: кавычки и теги в них не ломают разметку. */
export function dossierText(type: string, profile: Record<string, unknown>, imageCount: number, today: string): string {
  const rule = TYPE_RULES[type] ?? `Тип «${type}».`;
  return [
    `Сегодня: ${today}. Тип верификации: ${type}.`,
    rule,
    SIGNA_TYPES.has(type) ? 'Для этого типа сигна обязательна.' : 'Для этого типа сигна не требуется (signa_visible = null).',
    `Приложено изображений: ${imageCount} (идут следом).`,
    '<user_data>',
    JSON.stringify(profile).replace(/</g, '\\u003c'), // "</user_data>" внутри данных не закрывает блок
    '</user_data>',
  ].join('\n');
}
